'use strict';

const vscode = require('vscode');
const tokenStore = require('../../core/services/token-store');
const git = require('../../core/services/git');
const registry = require('../../core/providers/registry');
const { chatCompletion } = require('../../core/services/chat');

const COMMIT_PROMPT = `You are a git expert. Generate a concise commit message in English (conventional commits style: feat/fix/chore/refactor/docs/test/...) for the following diff. Reply ONLY with the commit message, no explanation, no markdown code block.

Diff:`;

async function generateCommitMessage(context) {
  let token;
  try {
    token = await tokenStore.getToken();
  } catch (e) {
    return vscode.window.showErrorMessage(`OpenGIT: ${e.message}`);
  }

  let diff;
  try {
    diff = await git.getGitDiff();
  } catch (e) {
    return vscode.window.showErrorMessage(`OpenGIT: ${e.message}`);
  }
  if (!diff?.trim()) {
    return vscode.window.showWarningMessage('OpenGIT: No git changes detected.');
  }

  try {
    const settingId = vscode.workspace.getConfiguration('openbyok').get('commitModel')?.toString().trim();
    const model = await registry.getDefault().resolveModelFor(token, settingId);
    const label = model.name || model.modelID;
    if (!settingId) {
      vscode.window.showInformationMessage(`OpenGIT: aucun commitModel configuré — utilisation du modèle le plus rapide (${label}).`);
    }
    vscode.window.withProgress(
      { location: vscode.ProgressLocation.Window, title: `OpenGIT: generating commit message (${label})…` },
      async () => {
        try {
          const message = await chatCompletion(model.baseURL, model.modelID, token, `${COMMIT_PROMPT}\n${diff}`);

          if (await git.fillScmInputBox(message)) {
            vscode.window.showInformationMessage(`Commit message generated by ${label} — inserted in the commit box.`);
            return;
          }

          // Git extension unavailable: show the message so the user can copy it.
          vscode.window.showInformationMessage(`Commit message generated by ${label}: ${message}`);
        } catch (e) {
          vscode.window.showErrorMessage(`OpenGIT: ${e.message}`);
        }
      }
    );
  } catch (e) {
    vscode.window.showErrorMessage(`OpenGIT: ${e.message}`);
  }
}

function register(context) {
  context.subscriptions.push(
    vscode.commands.registerCommand('opengit.generateCommitMessage', () => generateCommitMessage(context))
  );
}

module.exports = { register };
