'use strict';

const vscode = require('vscode');
const tokenStore = require('../../core/services/token-store');
const git = require('../../core/services/git');
const benchCache = require('../../core/services/bench-cache');
const benchmark = require('../benchmark/commands');
const modelResolver = require('../../core/services/model-resolver');
const commitGenerator = require('../../core/services/commit-generator');

async function generateCommitMessage(context) {
  let token;
  try {
    token = await tokenStore.getToken();
  } catch (e) {
    return vscode.window.showErrorMessage(`OpenBYOK: ${e.message}`);
  }

  let diff;
  try {
    diff = await git.getGitDiff();
  } catch (e) {
    return vscode.window.showErrorMessage(`OpenBYOK: ${e.message}`);
  }
  if (!diff?.trim()) {
    return vscode.window.showWarningMessage('OpenBYOK: No git changes detected.');
  }

  const history = await git.getGitLog(5);
  const cfg = vscode.workspace.getConfiguration('openbyok');
  const settingId = cfg.get('commitModel')?.toString().trim();
  const customPrompt = cfg.get('commitPrompt')?.toString().trim();

  // Informational message when no commitModel configured (fastest model used).
  let label;
  if (settingId) {
    label = settingId;
  } else {
    const best = modelResolver.bestCachedModel({ sortBy: 'spd' });
    if (!best) {
      return vscode.window.showWarningMessage('OpenBYOK: aucun modèle disponible pour générer un message de commit.');
    }
    label = best.name || best.modelID;
    vscode.window.showInformationMessage(`OpenBYOK: aucun commitModel configuré — utilisation du modèle le plus rapide (${label}).`);
  }

  try {
    vscode.window.withProgress(
      { location: vscode.ProgressLocation.Window, title: `OpenBYOK: generating commit message (${label})…` },
      async () => {
        try {
          const message = await commitGenerator({
            token,
            diff,
            history,
            settingId,
            customPrompt: customPrompt || undefined,
          });

          if (await git.fillScmInputBox(message)) {
            vscode.window.showInformationMessage(`Commit message generated by ${label} — inserted in the commit box.`);
            return;
          }

          // Git extension unavailable: show the message so the user can copy it.
          vscode.window.showInformationMessage(`Commit message generated by ${label}: ${message}`);
        } catch (e) {
          vscode.window.showErrorMessage(`OpenBYOK: ${e.message}`);
        }
      }
    );
  } catch (e) {
    vscode.window.showErrorMessage(`OpenBYOK: ${e.message}`);
  }
}

async function selectCommitModel() {
  let cache = benchCache.data();
  if (!cache?.results?.length) {
    const run = await vscode.window.showInformationMessage('No benchmark cache. Run benchmark now?', 'Run Benchmark');
    if (run === 'Run Benchmark') {
      const ok = await benchmark.runBenchmarkWithProgress();
      if (!ok) return;
      cache = benchCache.data();
    } else {
      return;
    }
  }
  const items = (cache?.results || [])
    .filter((r) => r?.modelID)
    .map((r) => ({
      label: r.name || r.modelID,
      description: `${r.providerID} · ${r.tokensPerSec ?? '?'} tok/s · TTFT ${r.ttftMs ?? '?'}ms`,
      modelID: r.modelID,
    }));
  if (items.length === 0) {
    vscode.window.showWarningMessage('No models in benchmark cache.');
    return;
  }
  const pick = await vscode.window.showQuickPick(items, {
    placeHolder: 'Select the model to use for commit message generation',
    title: 'OpenBYOK — Commit model',
  });
  if (!pick) return;
  const cfg = vscode.workspace.getConfiguration('openbyok');
  await cfg.update('commitModel', pick.modelID, vscode.ConfigurationTarget.Global);
  try { benchmark.updateStatusBar(); } catch (e) {}
  vscode.window.showInformationMessage(`Commit model set to ${pick.label} (${pick.modelID}).`);
}

function register(context) {
  context.subscriptions.push(
    vscode.commands.registerCommand('openbyok.generateCommitMessage', () => generateCommitMessage(context)),
    vscode.commands.registerCommand('openbyok.selectCommitModel', () => selectCommitModel()),
  );
}

module.exports = { register, generateCommitMessage, selectCommitModel };
